OUT = ROOT / "data" / "resorts.yaml"
CACHE = ROOT / "raw" / "build_resorts"
MARKER = "  # ---- generated by scripts/build_resorts.py from data/resort_seed.txt (edit the seed, not below) ----\n"
UA = "snow-forecast-resort-builder/0.2 (+https://github.com/TokenFlyAI/snow)"
