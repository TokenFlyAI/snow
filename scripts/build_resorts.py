#!/usr/bin/env python3
"""Build the generated part of data/resorts.yaml from data/resort_seed.txt.

For every seed line it looks up

  * coordinates: the centroid of the OpenStreetMap `landuse=winter_sports` polygon
    (Overpass API). Without such a polygon it falls back to the centroid of the
    OSM lifts (`aerialway=*`) around the seed position.
  * elevations: the Wikipedia "Infobox ski area" (top_elevation / base_elevation)
    when the article has one, otherwise the published figure in the seed file.
    Both are cross-checked against the lowest / highest OSM lift station on a
    digital elevation model (Open Topo Data, Mapzen terrain tiles).

`needs_review: true` is set when two sources disagree or a value is a guess; the
reason goes into `notes`. Network answers are cached in raw/build_resorts/, so a
re-run only asks for what is missing.

    python scripts/build_resorts.py            # writes data/resorts.yaml + raw/build_resorts/report.md
    python scripts/build_resorts.py --offline  # rebuild from cache only
"""
