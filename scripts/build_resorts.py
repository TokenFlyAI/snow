# ------------------------------------------------------------------ seed
def parse_seed(path: Path = SEED) -> list[dict]:
    rows = []
    for ln in path.read_text(encoding="utf-8").splitlines():
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        f = [x.strip() for x in ln.split("|")]
        if len(f) < 13:
            raise ValueError(f"bad seed line: {ln}")
        opts = {}
        for o in f[12].split(";"):
            o = o.strip()
            if not o:
                continue
            k, _, v = o.partition("=")
            opts[k.strip()] = v.strip() or True
        pname, _, tier = f[4].partition(":")

        def elev(s):
            return int(s.rstrip("?")), s.endswith("?")
        (b, bg), (t, tg) = elev(f[10]), elev(f[11])
        rows.append(dict(id=f[0], name=f[1], name_zh=f[2], destination=f[3] or None, passes={pname: tier},
                         country=f[5], state=f[6] or None, region=f[7], lat=float(f[8]), lon=float(f[9]),
                         base=b, top=t, base_guess=bg, top_guess=tg, opts=opts,
                         r_km=float(opts.get("r", 3.0))))
    ids = [r["id"] for r in rows]
    assert len(ids) == len(set(ids)), "duplicate ids in seed"
    return rows


# ------------------------------------------------------------------ helpers
def haversine_km(a_lat, a_lon, b_lat, b_lon) -> float:
    p = math.pi / 180
    x = (math.sin((b_lat - a_lat) * p / 2) ** 2
         + math.cos(a_lat * p) * math.cos(b_lat * p) * math.sin((b_lon - a_lon) * p / 2) ** 2)
    return 2 * 6371.0 * math.asin(math.sqrt(x))


STOP = {"ski", "resort", "resorts", "area", "the", "at", "mountain", "mountains", "mt", "mount", "snow", "park",
        "skigebiet", "domaine", "skiable", "de", "di", "la", "le", "les", "am", "and", "station"}


def tokens(s: str) -> set[str]:
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return {t for t in re.split(r"[^a-z0-9]+", s) if t and t not in STOP}


def name_match(resort: dict, osm_name: str) -> bool:
    if not osm_name:
        return False
    hint = resort["opts"].get("osm")
    cand = tokens(osm_name)
    for ref in ([hint] if isinstance(hint, str) else []) + [resort["name"], resort["id"].replace("-", " ")]:
        t = tokens(ref)
        if t and cand and (t <= cand or cand <= t):
            return True
    return False


class Net:
    def __init__(self, offline: bool):
        self.offline = offline
        self.client = httpx.Client(headers={"User-Agent": UA}, timeout=240.0)
        CACHE.mkdir(parents=True, exist_ok=True)

    def cached(self, kind: str, key: str, fetch):
        p = CACHE / f"{kind}_{hashlib.sha1(key.encode()).hexdigest()[:16]}.json"
        if p.exists():
            return json.loads(p.read_text())
        if self.offline:
            return None
        data = fetch()
        p.write_text(json.dumps(data))
        return data

    def overpass(self, query: str) -> dict:
        def fetch():
            delay = 20
            for attempt in range(6):
                try:
                    r = self.client.post(OVERPASS, data={"data": query})
                    if r.status_code == 200:
                        return r.json()
                    print(f"  overpass HTTP {r.status_code}, retry in {delay}s", file=sys.stderr)
                except httpx.HTTPError as e:
                    print(f"  overpass error {e}, retry in {delay}s", file=sys.stderr)
                time.sleep(delay)
                delay = min(delay * 2, 180)
            raise RuntimeError("overpass kept failing")
        out = self.cached("overpass", query, fetch)
        return out or {"elements": []}

    def elevations(self, pts: list[tuple[float, float]]) -> list[float | None]:
        out: list[float | None] = []
        for i in range(0, len(pts), 100):
            chunk = pts[i:i + 100]
            loc = "|".join(f"{la:.5f},{lo:.5f}" for la, lo in chunk)

            def fetch():
                for attempt in range(5):
                    r = self.client.get(TOPO, params={"locations": loc})
                    if r.status_code == 200:
                        time.sleep(1.1)   # public API: 1 request per second
                        return r.json()
                    time.sleep(5 * (attempt + 1))
                raise RuntimeError(f"opentopodata HTTP {r.status_code}")
            d = self.cached("dem", loc, fetch)
            out += [x.get("elevation") for x in d["results"]] if d else [None] * len(chunk)
        return out

    def wikitext(self, title: str) -> tuple[str, str] | None:
        def fetch():
            r = self.client.get(WIKI, params={"action": "query", "prop": "revisions", "rvprop": "content",
                                              "rvslots": "main", "rvsection": 0, "titles": title,
                                              "redirects": 1, "format": "json", "formatversion": 2})
            r.raise_for_status()
            time.sleep(0.2)
            return r.json()
        d = self.cached("wiki", title, fetch)
        try:
            page = d["query"]["pages"][0]
            return page["title"], page["revisions"][0]["slots"]["main"]["content"]
        except (KeyError, IndexError, TypeError):
            return None


# ------------------------------------------------------------------ Wikipedia infobox
def _num(s: str) -> float | None:
    s = s.replace(",", "").replace("&nbsp;", " ")
    m = re.search(r"-?\d+(?:\.\d+)?", s)
    return float(m.group()) if m else None


def parse_infobox_elev(text: str, field: str) -> int | None:
    m = re.search(rf"^\s*\|\s*{field}\s*=\s*(.+)$", text, re.M)
    if not m:
        return None
    v = m.group(1)
    c = re.search(r"\{\{\s*(?:convert|cvt)\s*\|\s*([\d,\.]+)\s*\|\s*(ft|m|feet|metres|meters)\b", v, re.I)
    if c:
        n, unit = _num(c.group(1)), c.group(2).lower()
    else:
        p = re.search(r"([\d,\.]+)\s*(?:&nbsp;)?\s*(ft|feet|m|metres|meters)\b", v, re.I)
        if not p:
            return None
        n, unit = _num(p.group(1)), p.group(2).lower()
    if n is None:
        return None
    return int(round(n * 0.3048)) if unit.startswith("f") else int(round(n))


def wiki_elevations(net: Net, r: dict) -> dict | None:
    if r["opts"].get("nowiki"):
        return None
    title = r["opts"].get("wiki") or r["name"]
    got = net.wikitext(title)
    if not got:
        return None
    real, text = got
    if not re.search(r"\{\{\s*Infobox ski (area|resort)", text, re.I):
        return None
    top, base = parse_infobox_elev(text, "top_elevation"), parse_infobox_elev(text, "base_elevation")
    if top is None or base is None or not (0 <= base < top <= 5000):
        return None
    return {"title": real, "base": base, "top": top}


# ------------------------------------------------------------------ OSM
def find_polygons(net: Net, rows: list[dict]) -> None:
    for i in range(0, len(rows), 12):
        batch = rows[i:i + 12]
        body = "".join(f'nwr["landuse"="winter_sports"](around:{int(max(r["r_km"], 3) * 1000 + 3000)},{r["lat"]},{r["lon"]});'
                       for r in batch)
        q = f"[out:json][timeout:180];({body});out center bb;"
        els = net.overpass(q)["elements"]
        print(f"polygons {i + len(batch)}/{len(rows)}: {len(els)} elements", file=sys.stderr)
        for r in batch:
            cands = []
            for e in els:
                b = e.get("bounds")
                # Overpass' own `center` is the middle of the bounding box, so derive it from `bb`
                c = e.get("center") or ({"lat": (b["minlat"] + b["maxlat"]) / 2, "lon": (b["minlon"] + b["maxlon"]) / 2} if b
                                        else {"lat": e["lat"], "lon": e["lon"]} if "lat" in e else None)
                if not c:
                    continue
                d = haversine_km(r["lat"], r["lon"], c["lat"], c["lon"])
                if d <= max(r["r_km"], 3) + 3:
                    nm = e.get("tags", {}).get("name") or e.get("tags", {}).get("name:en") or ""
                    cands.append(dict(d=d, name=nm, match=name_match(r, nm) or name_match(r, e.get("tags", {}).get("name:en", "")),
                                      lat=c["lat"], lon=c["lon"], bounds=e.get("bounds"), ref=f'{e["type"]} {e["id"]}'))
            named = sorted((c for c in cands if c["match"]), key=lambda c: c["d"])
            near = sorted((c for c in cands if c["d"] <= min(r["r_km"], 3.0)), key=lambda c: c["d"])
            r["poly"] = named[0] if named else (near[0] if near and not r["destination"] else None)
            r["poly_named"] = bool(named)
    # A polygon shared by several forecast points (one outline for a whole linked area such as
    # Zermatt-Cervinia or the 4 Vallées) would give them all the same position. Then every one of
    # them uses the lifts around its own search point instead.
    seen: dict[str, list[dict]] = {}
    for r in rows:
        if r.get("poly"):
            seen.setdefault(r["poly"]["ref"], []).append(r)
    for ref, rs in seen.items():
        if len(rs) > 1:
            for r in rs:
                r["poly"] = None
                r["poly_named"] = False
                r["shared_poly"] = ref


def find_lifts(net: Net, rows: list[dict]) -> None:
    for i in range(0, len(rows), 10):
        batch = rows[i:i + 10]
        body = ""
        for r in batch:
            p = r.get("poly")
            if p and p.get("bounds"):
                b = p["bounds"]
                half = haversine_km(b["minlat"], b["minlon"], b["maxlat"], b["maxlon"]) / 2
                r["_c"], r["_rad"] = (p["lat"], p["lon"]), min(max(half, 1.0) + 0.4, 10.0)
            else:
                r["_c"], r["_rad"] = (r["lat"], r["lon"]), r["r_km"]
            body += f'way["aerialway"~"{LIFT_RE}"](around:{int(r["_rad"] * 1000)},{r["_c"][0]},{r["_c"][1]});'
        q = f"[out:json][timeout:180];({body});out tags geom;"
        els = net.overpass(q)["elements"]
        print(f"lifts {i + len(batch)}/{len(rows)}: {len(els)} ways", file=sys.stderr)
        for r in batch:
            pts = []
            b = (r.get("poly") or {}).get("bounds")
            for e in els:
                g = e.get("geometry") or []
                if len(g) < 2:
                    continue
                a, z = g[0], g[-1]
                mid = ((a["lat"] + z["lat"]) / 2, (a["lon"] + z["lon"]) / 2)
                if b:
                    pad = 0.004
                    inside = (b["minlat"] - pad <= mid[0] <= b["maxlat"] + pad and b["minlon"] - pad <= mid[1] <= b["maxlon"] + pad)
                else:
                    inside = haversine_km(r["_c"][0], r["_c"][1], *mid) <= r["_rad"]
                if inside:
                    pts += [(a["lat"], a["lon"]), (z["lat"], z["lon"])]
            r["lift_pts"] = sorted(set((round(la, 5), round(lo, 5)) for la, lo in pts))
            r["n_lifts"] = len(pts) // 2


# ------------------------------------------------------------------ assemble
def resolve(net: Net, r: dict) -> dict:
    notes, sources, review = [], [], False

    # --- coordinates
    p = r.get("poly")
    if p:
        lat, lon = p["lat"], p["lon"]
        sources.append(f"OSM {p['ref']} '{p['name'] or 'unnamed'}' (landuse=winter_sports, centre of bounds)")
        if not r["poly_named"]:
            notes.append(f"OSM polygon chosen by distance ({p['d']:.1f} km from the search point), its name does not match.")
    elif r["n_lifts"] >= 3:
        lat = sum(q[0] for q in r["lift_pts"]) / len(r["lift_pts"])
        lon = sum(q[1] for q in r["lift_pts"]) / len(r["lift_pts"])
        why = (f"the landuse=winter_sports polygon {r['shared_poly']} covers several forecast points" if r.get("shared_poly")
               else "no landuse=winter_sports polygon for this area")
        sources.append(f"OSM centroid of {r['n_lifts']} lifts within {r['r_km']:g} km ({why})")
        if haversine_km(lat, lon, r["lat"], r["lon"]) > max(2.5, r["r_km"] * 0.6):
            review = True
            notes.append("Lift centroid is far from the expected position; neighbouring ski areas may be mixed in.")
    else:
        lat, lon = r["lat"], r["lon"]
        review = True
        sources.append("coordinates: approximate, no OSM polygon or lifts found")
        notes.append("Coordinates are a guess (nothing usable in OSM).")

    # --- elevations
    dem = None
    if r["n_lifts"] >= 2:
        ev = [e for e in net.elevations(r["lift_pts"]) if e is not None]
        if len(ev) >= 4:
            dem = (int(round(min(ev))), int(round(max(ev))))
    wk = wiki_elevations(net, r)
    seed_ok = not (r["base_guess"] or r["top_guess"])

    def near_dem(b, t):
        return abs(b - dem[0]) + abs(t - dem[1]) if dem else 0

    if wk:
        base, top = wk["base"], wk["top"]
        sources.append(f"Wikipedia '{wk['title']}': base {wk['base']} m, top {wk['top']} m")
        if seed_ok and (abs(wk["base"] - r["base"]) > SOURCE_TOL_M or abs(wk["top"] - r["top"]) > SOURCE_TOL_M):
            review = True
            notes.append(f"Elevation sources disagree: Wikipedia {wk['base']}-{wk['top']} m, resort figures {r['base']}-{r['top']} m.")
            if dem and near_dem(r["base"], r["top"]) < near_dem(base, top):
                base, top = r["base"], r["top"]
    elif seed_ok:
        base, top = r["base"], r["top"]
        sources.append(f"resort-published figures: base {base} m, top {top} m (no Wikipedia infobox)")
    elif dem:
        base = dem[0] if r["base_guess"] else r["base"]
        top = dem[1] if r["top_guess"] else r["top"]
        sources.append("elevation from OSM lift stations on the Mapzen DEM" + ("" if r["base_guess"] and r["top_guess"]
                       else f" for the missing value, published figure for the other (base {r['base']}, top {r['top']})"))
    else:
        base, top = r["base"], r["top"]
        review = True
        sources.append("elevation: rough estimate")
        notes.append("Elevations are a guess (no Wikipedia infobox, no OSM lifts).")
    if dem:
        sources.append(f"OSM lift stations on DEM: {dem[0]}-{dem[1]} m ({r['n_lifts']} lifts)")
        # a published summit above the highest lift is normal (hike-to terrain), so that side is more tolerant
        if (wk or seed_ok) and (abs(base - dem[0]) > ELEV_TOL_M or top - dem[1] > TOP_ABOVE_LIFTS_TOL_M
                                or dem[1] - top > TOP_BELOW_LIFTS_TOL_M):
            review = True
            notes.append(f"Published {base}-{top} m vs lift stations on the DEM {dem[0]}-{dem[1]} m.")
    elif wk is None and seed_ok:
        review = True
        notes.append("Elevations come from a single unverified source (no Wikipedia infobox, no OSM lifts to check against).")
    if top - base < 20:
        top = base + 20
    mid = int(round((base + top) / 2))

    tz = r["opts"].get("tz") or TZ.get((r["country"], r["state"])) or TZ_COUNTRY[r["country"]]
    return dict(id=r["id"], name=r["name"], name_zh=r["name_zh"], destination=r["destination"], passes=r["passes"],
                country=r["country"], state=r["state"], region=r["region"], lat=round(lat, 4), lon=round(lon, 4),
                elevation_m=dict(base=int(base), mid=mid, summit=int(top)), timezone=tz,
                needs_review=review, notes=" ".join(notes) or None, sources=sources,
                _dem=dem, _wiki=wk, _moved_km=round(haversine_km(lat, lon, r["lat"], r["lon"]), 1))


def q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def to_yaml(e: dict) -> str:
    L = [f"  - id: {e['id']}", f"    name: {q(e['name'])}", f"    name_zh: {q(e['name_zh'])}"]
    if e["destination"]:
        L.append(f"    destination: {e['destination']}")
    L.append("    passes: {" + ", ".join(f"{k}: {v}" for k, v in e["passes"].items()) + "}")
    L.append(f"    country: {e['country']}")
    if e["state"]:
        L.append(f"    state: {q(e['state'])}")
    L += [f"    region: {e['region']}", f"    lat: {e['lat']:.4f}", f"    lon: {e['lon']:.4f}",
          "    elevation_m: {base: %d, mid: %d, summit: %d}" % (e["elevation_m"]["base"], e["elevation_m"]["mid"], e["elevation_m"]["summit"]),
          f"    timezone: {e['timezone']}", "    snotel: null"]
    if e["needs_review"]:
        L.append("    needs_review: true")
    if e["notes"]:
        L.append(f"    notes: {q(e['notes'])}")
    L.append("    sources: [" + ", ".join(q(s) for s in e["sources"]) + "]")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--offline", action="store_true", help="use cached answers only")
    ap.add_argument("--only", default="", help="comma-separated ids (debugging; does not write the YAML)")
    args = ap.parse_args()
    rows = parse_seed()
    if args.only:
        keep = set(args.only.split(","))
        rows = [r for r in rows if r["id"] in keep]
    net = Net(args.offline)
    find_polygons(net, rows)
    find_lifts(net, rows)
    entries = []
    for n, r in enumerate(rows, 1):
        entries.append(resolve(net, r))
        if n % 25 == 0:
            print(f"resolved {n}/{len(rows)}", file=sys.stderr)

    report = ["| id | needs_review | moved km | elevation used | DEM lifts | Wikipedia | notes |", "|---|---|---|---|---|---|---|"]
    for e in entries:
        el = e["elevation_m"]
        report.append(f"| {e['id']} | {'YES' if e['needs_review'] else ''} | {e['_moved_km']} | {el['base']}-{el['summit']} | "
                      f"{'%d-%d' % e['_dem'] if e['_dem'] else '-'} | {'%d-%d' % (e['_wiki']['base'], e['_wiki']['top']) if e['_wiki'] else '-'} | {e['notes'] or ''} |")
    (CACHE / "report.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    n_rev = sum(e["needs_review"] for e in entries)
    print(f"{len(entries)} entries, {n_rev} need review -> {CACHE / 'report.md'}", file=sys.stderr)
    if args.only:
        print("\n".join(to_yaml(e) for e in entries))
        return 0

    text = OUT.read_text(encoding="utf-8")
    head = text.split(MARKER)[0].rstrip("\n") + "\n\n"
    OUT.write_text(head + MARKER + "\n" + "\n".join(to_yaml(e) for e in entries), encoding="utf-8")
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
