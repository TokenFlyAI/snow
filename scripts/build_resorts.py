TOPO = "https://api.opentopodata.org/v1/mapzen"
WIKI = "https://en.wikipedia.org/w/api.php"
LIFT_RE = "^(chair_lift|gondola|cable_car|drag_lift|t-bar|j-bar|platter|rope_tow|magic_carpet|mixed_lift)$"

ELEV_TOL_M = 150          # published base vs lowest lift station on the DEM
TOP_ABOVE_LIFTS_TOL_M = 250
TOP_BELOW_LIFTS_TOL_M = 100
SOURCE_TOL_M = 60         # Wikipedia vs the figure in the seed file

