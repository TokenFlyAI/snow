"""Match resorts to SNOTEL stations: writes data/stations.yaml (design doc A1).

    python scripts/match_stations.py                     # station list from the AWDB API
    python scripts/match_stations.py --stations FILE     # or from a saved AWDB /stations dump

Rules: stations within 15 km of the resort, closest in height to the resort's mid elevation first,
at most 3. Grades (dz against mid elevation):
    A  < 5 km and |dz| < 300 m   on the mountain
    B  < 15 km and |dz| < 500 m
    C  the rest within 15 km; shown, but not used for scoring or training
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from pipeline.verify import obs_snotel  # noqa: E402

FT = 0.3048
MAX_KM = 15.0
MAX_STATIONS = 3


def km(lat1, lon1, lat2, lon2) -> float:
    p1, p2 = math.radians(lat1), math.radians(lat2)
    a = math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(math.radians(lon2 - lon1) / 2) ** 2
    return 6371.0 * 2 * math.asin(math.sqrt(a))


def grade(d_km: float, dz_m: float) -> str:
    if d_km < 5 and abs(dz_m) < 300:
        return "A"
    if d_km < 15 and abs(dz_m) < 500:
        return "B"
    return "C"


def match(resorts: list[dict], stations: list[dict]) -> dict[str, list[dict]]:
    out = {}
    for r in resorts:
        mid = r["elevation_m"]["mid"]
        cands = []
        for s in stations:
            d = km(r["lat"], r["lon"], s["latitude"], s["longitude"])
            if d > MAX_KM:
                continue
            elev = s["elevation"] * FT
            dz = elev - mid
            cands.append((grade(d, dz), abs(dz), d, s, elev, dz))
        cands.sort(key=lambda c: (c[0], c[1] + 30 * c[2]))      # best grade, then closest in height and distance
        if cands:
            out[r["id"]] = [{"triplet": s["stationTriplet"], "name": s["name"], "lat": round(s["latitude"], 5),
                             "lon": round(s["longitude"], 5), "elevation_m": round(elev),
                             "utc_offset_h": s.get("dataTimeZone", -8.0), "km": round(d, 1), "dz_m": round(dz),
                             "grade": g}
                            for g, _, d, s, elev, dz in cands[:MAX_STATIONS]]
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stations", help="saved AWDB /stations JSON")
    ap.add_argument("--out", default=str(ROOT / "data" / "stations.yaml"))
    a = ap.parse_args()
    stations = json.loads(Path(a.stations).read_text()) if a.stations else obs_snotel.stations()
    stations = [s for s in stations if s.get("networkCode") == "SNTL" and str(s.get("endDate", "2100")).startswith("2100")]
    resorts = [r for r in yaml.safe_load((ROOT / "data" / "resorts.yaml").read_text())["resorts"] if r["country"] == "US"]
    m = match(resorts, stations)

    by_grade = {"A": 0, "B": 0, "C": 0}
    for rid, sts in m.items():
        by_grade[sts[0]["grade"]] += 1
    header = (f"# Generated by scripts/match_stations.py on {date.today().isoformat()} from the NRCS AWDB station list.\n"
              "# Do not edit by hand: re-run the script. Per resort: SNOTEL stations within 15 km, best first.\n"
              "# grade A: < 5 km and |dz| < 300 m from mid elevation; B: < 15 km and |dz| < 500 m; C: shown only.\n"
              "# utc_offset_h: the station's fixed data time zone (no daylight saving).\n")
    body = {"source": obs_snotel.SOURCE, "resorts": dict(sorted(m.items()))}
    Path(a.out).write_text(header + yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")

    for r in resorts:
        sts = m.get(r["id"])
        best = sts[0] if sts else None
        note = ""
        if r.get("snotel") and (not sts or r["snotel"] not in {s["triplet"] for s in sts}):
            note = f"  (resorts.yaml snotel {r['snotel']} not matched)"
        print("%-28s %-14s %-12s %-26s %6s %7s %s%s" % (
            r["id"], r["region"], best["triplet"] if best else "-", best["name"][:26] if best else "",
            f"{best['km']}km" if best else "", f"{best['dz_m']:+d}m" if best else "", best["grade"] if best else "",
            note))
    print(f"\n{len(resorts)} US resorts: {len(m)} with a station within {MAX_KM:.0f} km; best grade A {by_grade['A']}, "
          f"B {by_grade['B']}, C {by_grade['C']}; {len({s['triplet'] for v in m.values() for s in v})} distinct stations")


if __name__ == "__main__":
    main()
