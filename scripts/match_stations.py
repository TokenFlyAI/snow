"""Match resorts to measuring stations: writes data/stations.yaml (design doc A1).

    python scripts/match_stations.py                     # station lists from the AWDB and SLF APIs
    python scripts/match_stations.py --stations FILE     # SNOTEL list from a saved AWDB /stations dump

Sources: USDA NRCS SNOTEL (US resorts; id = the AWDB triplet) and SLF IMIS snow stations
(Switzerland, also used for resorts across the border; id = "SLF:<code>").

Rules: stations within 15 km of the resort, closest in height to the resort's mid elevation first,
at most 3. Grades (dz against mid elevation):
    A  < 5 km and |dz| < 300 m   on the mountain
    B  < 15 km and |dz| < 500 m
    C  the rest within 15 km; shown, but not used for scoring or training
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from pipeline.verify import obs_slf, obs_snotel  # noqa: E402

FT = 0.3048
MAX_KM = 15.0
MAX_STATIONS = 3


def km(lat1, lon1, lat2, lon2) -> float:
    p1, p2 = math.radians(lat1), math.radians(lat2)
    a = math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(math.radians(lon2 - lon1) / 2) ** 2
    return 6371.0 * 2 * math.asin(math.sqrt(a))


def grade(d_km: float, dz_m: float) -> str:
    if d_km < 5 and abs(dz_m) < 300:
        return "A"
    if d_km < 15 and abs(dz_m) < 500:
        return "B"
    return "C"


def snotel_stations(raw: list[dict]) -> list[dict]:
    """AWDB station records -> common form (elevation in feet -> m)."""
    return [{"id": s["stationTriplet"], "name": s["name"], "lat": s["latitude"], "lon": s["longitude"],
             "elevation_m": s["elevation"] * FT, "utc_offset_h": s.get("dataTimeZone", -8.0), "source": "snotel"}
            for s in raw if s.get("networkCode") == "SNTL" and str(s.get("endDate", "2100")).startswith("2100")]


def slf_stations(raw: list[dict]) -> list[dict]:
    return [{**s, "utc_offset_h": 0.0, "source": "slf"} for s in raw]


def match(resorts: list[dict], stations: list[dict]) -> dict[str, list[dict]]:
    """Stations in common form ({id, name, lat, lon, elevation_m, utc_offset_h, source}) per resort."""
    out = {}
    for r in resorts:
        mid = r["elevation_m"]["mid"]
        cands = []
        for s in stations:
            if s["source"] == "snotel" and r["country"] != "US":
                continue
            d = km(r["lat"], r["lon"], s["lat"], s["lon"])
            if d > MAX_KM:
                continue
            dz = s["elevation_m"] - mid
            cands.append((grade(d, dz), abs(dz), d, s, dz))
        cands.sort(key=lambda c: (c[0], c[1] + 30 * c[2]))      # best grade, then closest in height and distance
        if cands:
            out[r["id"]] = [{"triplet": s["id"], "name": s["name"], "lat": round(s["lat"], 5),
                             "lon": round(s["lon"], 5), "elevation_m": round(s["elevation_m"]),
                             "utc_offset_h": s["utc_offset_h"], "km": round(d, 1), "dz_m": round(dz),
                             "grade": g}
                            for g, _, d, s, dz in cands[:MAX_STATIONS]]
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stations", help="saved AWDB /stations JSON")
    ap.add_argument("--out", default=str(ROOT / "data" / "stations.yaml"))
    a = ap.parse_args()
    raw = json.loads(Path(a.stations).read_text()) if a.stations else obs_snotel.stations()
    stations = snotel_stations(raw) + slf_stations(obs_slf.stations())
    resorts = yaml.safe_load((ROOT / "data" / "resorts.yaml").read_text())["resorts"]
    m = match(resorts, stations)
    resorts = [r for r in resorts if r["id"] in m]

    by_grade = {"A": 0, "B": 0, "C": 0}
    for rid, sts in m.items():
        by_grade[sts[0]["grade"]] += 1
    header = (f"# Generated by scripts/match_stations.py on {date.today().isoformat()} from the NRCS AWDB and SLF station lists.\n"
              "# Do not edit by hand: re-run the script. Per resort: stations within 15 km, best first.\n"
              "# triplet: station id (SNOTEL triplet, or SLF:<code> for SLF IMIS stations).\n"
              "# grade A: < 5 km and |dz| < 300 m from mid elevation; B: < 15 km and |dz| < 500 m; C: shown only.\n"
              "# utc_offset_h: the station's fixed data time zone (no daylight saving; SLF data is UTC).\n")
    body = {"sources": [obs_snotel.SOURCE, obs_slf.SOURCE], "resorts": dict(sorted(m.items()))}
    Path(a.out).write_text(header + yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")

    for r in resorts:
        sts = m.get(r["id"])
        best = sts[0] if sts else None
        note = ""
        if r.get("snotel") and (not sts or r["snotel"] not in {s["triplet"] for s in sts}):
            note = f"  (resorts.yaml snotel {r['snotel']} not matched)"
        print("%-28s %-14s %-12s %-26s %6s %7s %s%s" % (
            r["id"], r["region"], best["triplet"] if best else "-", best["name"][:26] if best else "",
            f"{best['km']}km" if best else "", f"{best['dz_m']:+d}m" if best else "", best["grade"] if best else "",
            note))
    print(f"\n{len(m)} resorts with a station within {MAX_KM:.0f} km; best grade A {by_grade['A']}, "
          f"B {by_grade['B']}, C {by_grade['C']}; {len({s['triplet'] for v in m.values() for s in v})} distinct stations")


if __name__ == "__main__":
    main()
